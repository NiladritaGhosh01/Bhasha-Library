import React, { useState } from 'react';

export default function StoryStudio({ onPublishStory, onCancel, t, langMode }) {
  const [titleEn, setTitleEn] = useState('');
  const [titleBn, setTitleBn] = useState('');
  const [genre, setGenre] = useState('Folklore');
  const [tone, setTone] = useState('Folklore & Nostalgic');
  const [prompt, setPrompt] = useState('');
  const [authorName, setAuthorName] = useState('Community Storyteller');

  const [englishText, setEnglishText] = useState('');
  const [banglaText, setBanglaText] = useState('');
  const [generatedVocab, setGeneratedVocab] = useState([]);
  const [isGenerating, setIsGenerating] = useState(false);
  const [aiModelNotice, setAiModelNotice] = useState(null);

  const presets = [
    {
      en: 'The Tea Stall on Cloud Nine',
      bn: 'মেঘের ওপর চায়ের দোকান',
      genre: 'Folklore',
      prompt: 'A warm roadside tea stall in Darjeeling that floats on morning mist.'
    },
    {
      en: 'The Robot and the Clay Potter',
      bn: 'রোবট ও মৃৎশিল্পী',
      genre: 'Sci-Fi',
      prompt: 'In Kumartuli 2090, a cybernetic apprentice learns the art of terracotta idols.'
    }
  ];

  const handleAIGenerate = async () => {
    if (!prompt.trim() && !titleEn.trim() && !titleBn.trim()) {
      alert('Please provide a prompt or title.');
      return;
    }

    setIsGenerating(true);
    setAiModelNotice(null);

    try {
      const res = await fetch('http://localhost:5000/api/ai/generate', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          prompt: prompt || titleEn || titleBn,
          title: titleEn || titleBn,
          genre,
          tone
        })
      });

      if (res.ok) {
        const json = await res.json();
        if (json.data) {
          const d = json.data;
          setTitleEn(d.title?.en || titleEn);
          setTitleBn(d.title?.bn || titleBn);

          if (d.paragraphs && Array.isArray(d.paragraphs)) {
            setEnglishText(d.paragraphs.map(p => p.en).join('\n\n'));
            setBanglaText(d.paragraphs.map(p => p.bn).join('\n\n'));
          }

          if (d.vocabulary) {
            setGeneratedVocab(d.vocabulary);
          }

          if (json.isLiveAI) {
            setAiModelNotice('✨ Generated by Gemini Flash API');
          } else if (d.note) {
            setAiModelNotice(d.note);
          }
          setIsGenerating(false);
          return;
        }
      }
    } catch (err) {
      console.warn('Backend AI endpoint unreachable; utilizing client fallback.');
    }

    // Local fallback if backend is offline
    setTimeout(() => {
      const generatedTitleEn = titleEn || 'The Whispering River of Bengal';
      const generatedTitleBn = titleBn || 'বাংলার নদীর ফিসফিসানি';

      const generatedEn = `On the quiet edges of the river, when the evening lamps flickered against the darkening water, ancient memories began to stir.\n\nA solitary boy stood on the wooden jetty, watching dragonflies skim across water lilies. He carried a small brass flute wrapped in indigo cotton, waiting for the dusk breeze to carry his tune across the marshland.`;

      const generatedBn = `নদীর শান্ত কূলে যখন সন্ধ্যার প্রদীপগুলো কালচে জলের বিপরীতে টিমটিম করে জ্বলত, তখন যেন প্রাচীন স্মৃতিরা জেগে উঠত।\n\nএকটি একাকী ছেলে কাঠের ঘাটে দাঁড়িয়ে শাপলার ওপর দিয়ে উড়ে যাওয়া ফড়িংদের খেলা দেখছিল। তার হাতে ছিল নীল সুতোয় জড়ানো একটি ছোট পিতলের বাঁশি, সে অপেক্ষা করছিল গোধূলির দখিন বাতাসের।`;

      setTitleEn(generatedTitleEn);
      setTitleBn(generatedTitleBn);
      setEnglishText(generatedEn);
      setBanglaText(generatedBn);
      setGeneratedVocab([
        { word: 'Jetty', bn: 'কাঠের ঘাট', note: 'Landing pier' },
        { word: 'Dusk', bn: 'গোধূলি', note: 'Twilight time' }
      ]);
      setIsGenerating(false);
    }, 1200);
  };

  const handleSubmit = (e) => {
    e.preventDefault();

    if (!titleEn.trim() && !titleBn.trim()) return;
    if (!englishText.trim() && !banglaText.trim()) return;

    const enParagraphs = englishText.split('\n\n').filter(p => p.trim());
    const bnParagraphs = banglaText.split('\n\n').filter(p => p.trim());
    const maxLen = Math.max(enParagraphs.length, bnParagraphs.length, 1);

    const paragraphs = [];
    for (let i = 0; i < maxLen; i++) {
      paragraphs.push({
        en: enParagraphs[i] || '',
        bn: bnParagraphs[i] || ''
      });
    }

    const newStory = {
      id: Date.now().toString(),
      genre,
      genreBn: genre === 'Folklore' ? 'লোকগাথা' : genre === 'Sci-Fi' ? 'কল্পবিজ্ঞান' : 'সাহিত্য',
      readTime: '3 min',
      likes: 1,
      title: {
        en: titleEn || 'Untitled Story',
        bn: titleBn || titleEn || 'নতুন গল্প'
      },
      synopsis: {
        en: enParagraphs[0]?.slice(0, 120) + '...' || '',
        bn: bnParagraphs[0]?.slice(0, 120) + '...' || ''
      },
      author: authorName || 'Author',
      date: 'Just now',
      languages: ['en', 'bn'],
      paragraphs,
      vocabulary: generatedVocab.length > 0 ? generatedVocab : [
        { word: 'Harmony', bn: 'ঐকতান', note: 'Pleasing arrangement of parts' }
      ]
    };

    onPublishStory(newStory);
  };

  return (
    <div className="studio-canvas">
      <header className="studio-minimal-header">
        <span className="studio-chip">{t.studio.badge}</span>
        <h2>{t.studio.title}</h2>
        <p>{t.studio.subtitle}</p>
        {aiModelNotice && (
          <div className="ai-model-tag">
            <span>{aiModelNotice}</span>
          </div>
        )}
      </header>

      {/* Minimal Preset Row */}
      <div className="minimal-preset-row">
        <span className="preset-caption">{t.studio.presetsLabel}</span>
        {presets.map((p, i) => (
          <button
            key={i}
            type="button"
            className="preset-pill"
            onClick={() => {
              setTitleEn(p.en);
              setTitleBn(p.bn);
              setGenre(p.genre);
              setPrompt(p.prompt);
            }}
          >
            {langMode === 'bn' ? p.bn : p.en}
          </button>
        ))}
      </div>

      <form onSubmit={handleSubmit} className="studio-glass-form">
        <div className="studio-grid-two">
          <div className="input-block">
            <label>{t.studio.titleEnLabel}</label>
            <input
              type="text"
              placeholder="e.g. The Quiet River"
              value={titleEn}
              onChange={(e) => setTitleEn(e.target.value)}
            />
          </div>

          <div className="input-block">
            <label className="bangla-font">{t.studio.titleBnLabel}</label>
            <input
              type="text"
              className="bangla-font"
              placeholder="যেমন: শান্ত নদী"
              value={titleBn}
              onChange={(e) => setTitleBn(e.target.value)}
            />
          </div>
        </div>

        {/* Premise & AI Generation */}
        <div className="ai-premise-card">
          <label>{t.studio.premiseLabel}</label>
          <textarea
            rows="2"
            placeholder={t.studio.premisePlaceholder}
            value={prompt}
            onChange={(e) => setPrompt(e.target.value)}
          />
          <div className="generate-row">
            <button
              type="button"
              className={`generate-btn ${isGenerating ? 'generating' : ''}`}
              onClick={handleAIGenerate}
              disabled={isGenerating}
            >
              {isGenerating ? (
                <>
                  <span className="mini-spinner"></span>
                  <span>{t.studio.generating}</span>
                </>
              ) : (
                <span>⚡ {t.studio.generateBtn}</span>
              )}
            </button>
          </div>
        </div>

        {/* Side-by-Side Manuscript textareas */}
        <div className="studio-grid-two editors">
          <div className="editor-pane">
            <span className="editor-tag">{t.studio.enEditorTitle}</span>
            <textarea
              rows="10"
              placeholder={t.studio.editorEnPlaceholder}
              value={englishText}
              onChange={(e) => setEnglishText(e.target.value)}
            />
          </div>

          <div className="editor-pane">
            <span className="editor-tag bangla-font">{t.studio.bnEditorTitle}</span>
            <textarea
              className="bangla-font"
              rows="10"
              placeholder={t.studio.editorBnPlaceholder}
              value={banglaText}
              onChange={(e) => setBanglaText(e.target.value)}
            />
          </div>
        </div>

        <div className="studio-actions-bar">
          <button type="button" className="glass-btn" onClick={onCancel}>
            {t.studio.cancelBtn}
          </button>
          <button type="submit" className="minimal-cta-btn">
            {t.studio.publishBtn}
          </button>
        </div>
      </form>
    </div>
  );
}
